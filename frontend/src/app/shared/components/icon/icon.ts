export type IconName = keyof typeof STROKE_ICONS | keyof typeof FILLED_ICONS;

/** Picks an icon for a social platform name ("GitHub", "LinkedIn", "X"...). */
export function platformIcon(platform: string): IconName {
  const p = platform.trim().toLowerCase();
  if (p === 'github') return 'github';
  if (p === 'linkedin') return 'linkedin';
  if (p === 'x' || p === 'twitter') return 'x-logo';
  if (p === 'instagram' || p === 'insta') return 'instagram';
  if (p === 'whatsapp' || p === 'whats app') return 'whatsapp';
  if (p === 'email' || p === 'mail') return 'mail';
  return 'globe';
}

